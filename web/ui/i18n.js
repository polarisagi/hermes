function getSystemLanguage() {
    const lang = localStorage.getItem('polarisagi_lang');
    if (lang && ['zh', 'en'].includes(lang)) {
        return lang;
    }
    return navigator.language.startsWith('zh') ? 'zh' : 'en';
}

function setSystemLanguage(lang) {
    localStorage.setItem('polarisagi_lang', lang);
    window.location.reload();
}

function getSystemTheme() {
    const theme = localStorage.getItem('polarisagi_theme');
    if (theme && ['light', 'dark', 'system'].includes(theme)) {
        return theme;
    }
    return 'system';
}

function applyTheme(theme) {
    localStorage.setItem('polarisagi_theme', theme);
    const isDark = theme === 'dark' || (theme === 'system' && window.matchMedia('(prefers-color-scheme: dark)').matches);
    
    if (isDark) {
        document.documentElement.classList.add('dark');
        const fpDark = document.getElementById('flatpickr-dark-theme');
        if (fpDark) fpDark.removeAttribute('disabled');
    } else {
        document.documentElement.classList.remove('dark');
        const fpDark = document.getElementById('flatpickr-dark-theme');
        if (fpDark) fpDark.setAttribute('disabled', 'true');
    }
}

// Watch for system theme changes
window.matchMedia('(prefers-color-scheme: dark)').addEventListener('change', e => {
    if (getSystemTheme() === 'system') {
        applyTheme('system');
    }
});

// Initial apply
applyTheme(getSystemTheme());
